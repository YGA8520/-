#!/usr/bin/env python3
"""Scan my-fonts/fonts and (re)generate the catalog the skill reads.

  python3 tools/build_catalog.py            -> my-fonts/catalog.json + my-fonts/FONTS.md
  python3 tools/build_catalog.py --check    -> print the summary only, write nothing

Per-family judgement (category, what it is good for, what to avoid) is NOT guessed from the
files: put it in font-library/notes.json, keyed by the family name exactly as the catalog prints it.
"""
import argparse, collections, json, os, sys

try:
    from fontTools.ttLib import TTCollection, TTFont
except ImportError:
    sys.exit('fonttools is missing:  pip install fonttools')

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILL = os.path.join(ROOT, 'my-fonts')
EXTS = ('.ttf', '.otf', '.woff', '.woff2', '.ttc')

HEBREW_LETTERS = set(range(0x05D0, 0x05EB))                      # alef .. tav incl. final forms (27)
NIQQUD = set(range(0x05B0, 0x05BD)) | {0x05C1, 0x05C2}           # vowel points, shin/sin dots
TAAMIM = set(range(0x0591, 0x05AF))                              # cantillation marks
HEB_EXTRAS = {0x05BE, 0x05F3, 0x05F4, 0x20AA}                    # maqaf, geresh, gershayim, shekel sign
LATIN = set(range(0x41, 0x5B)) | set(range(0x61, 0x7B))
DIGITS = set(range(0x30, 0x3A))
SCRIPTS = {'cyrillic': set(range(0x0410, 0x0450)), 'greek': set(range(0x03B1, 0x03CA)), 'arabic': set(range(0x0627, 0x064B))}


def name(font, *ids):
    for i in ids:
        r = font['name'].getName(i, 3, 1, 0x409) or font['name'].getName(i, 1, 0, 0)
        if r:
            try:
                s = r.toUnicode().strip()
            except Exception:
                continue
            if s:
                return s
    return ''


def level(cmap, want):
    have = len(want & cmap)
    return 'full' if have == len(want) else 'partial' if have else 'none'


def describe(font, path):
    cmap = set(font.getBestCmap() or {})
    os2 = font['OS/2'] if 'OS/2' in font else None
    weight = int(getattr(os2, 'usWeightClass', 400) or 400)
    italic = bool(os2 and os2.fsSelection & 1) or bool('head' in font and font['head'].macStyle & 2)
    axes = {}
    if 'fvar' in font:
        axes = {a.axisTag: [a.minValue, a.defaultValue, a.maxValue] for a in font['fvar'].axes}
        if 'wght' in axes:
            weight = int(axes['wght'][1])
    family = name(font, 16, 1) or os.path.splitext(os.path.basename(path))[0]
    style = name(font, 17, 2) or ('Italic' if italic else 'Regular')
    return {
        'family': family, 'style': style, 'full_name': name(font, 4), 'weight': weight, 'italic': italic,
        'variable_axes': axes, 'monospace': bool('post' in font and font['post'].isFixedPitch),
        'glyphs': len(font.getGlyphOrder()),
        'hebrew': level(cmap, HEBREW_LETTERS), 'niqqud': level(cmap, NIQQUD), 'taamim': level(cmap, TAAMIM),
        'hebrew_extras': level(cmap, HEB_EXTRAS), 'latin': level(cmap, LATIN), 'digits': level(cmap, DIGITS),
        **{k: level(cmap, v) for k, v in SCRIPTS.items()},
        'license': name(font, 13)[:300], 'license_url': name(font, 14), 'designer': name(font, 9), 'version': name(font, 5),
    }


def scan(fonts_dir):
    rows = []
    for dp, _, files in os.walk(fonts_dir):
        for f in sorted(files):
            if not f.lower().endswith(EXTS):
                continue
            path = os.path.join(dp, f)
            rel = os.path.relpath(path, SKILL).replace(os.sep, '/')
            try:
                fonts = list(TTCollection(path).fonts) if f.lower().endswith('.ttc') else [TTFont(path, lazy=True)]
                for i, font in enumerate(fonts):
                    d = describe(font, path)
                    d['file'] = rel + ('#%d' % i if len(fonts) > 1 else '')
                    d['bytes'] = os.path.getsize(path)
                    rows.append(d)
            except Exception as e:
                print('! cannot read %s: %s' % (rel, e), file=sys.stderr)
    return rows


def group(rows):
    fam = collections.OrderedDict()
    for r in sorted(rows, key=lambda r: (r['family'].lower(), r['weight'], r['italic'])):
        fam.setdefault(r['family'], []).append(r)
    return fam


def ticks(v):
    return {'full': '✔', 'partial': '◐', 'none': '—'}[v]


def markdown(fam, notes):
    L = ['# Font catalog', '',
         'Generated by `font-library/tools/build_catalog.py` — do not edit by hand (edit `font-library/notes.json` and regenerate).', '',
         'Legend: ✔ full · ◐ partial · — none. Hebrew = 27 letters incl. finals; Niqqud = vowel points; Taamim = cantillation; '
         'Marks = maqaf, geresh, gershayim, ₪.', '',
         '| Family | Styles | Hebrew | Niqqud | Taamim | Marks | Latin | Category | Good for | Avoid |', '|---|---|:-:|:-:|:-:|:-:|:-:|---|---|---|']
    for name_, rs in fam.items():
        n = notes.get(name_, {})
        styles = ', '.join(sorted({('%d%s' % (r['weight'], 'i' if r['italic'] else '')) + ('v' if r['variable_axes'] else '') for r in rs}))
        best = lambda k: ticks(max((r[k] for r in rs), key=['none', 'partial', 'full'].index))
        L.append('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
            name_, styles, best('hebrew'), best('niqqud'), best('taamim'), best('hebrew_extras'), best('latin'),
            n.get('category', '*(not set)*'), n.get('use', ''), n.get('avoid', '')))
    L += ['', 'Style codes: weight (100–900), `i` = italic, `v` = variable font. Files and exact names: `catalog.json`.', '']
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fonts-dir', default=os.path.join(SKILL, 'fonts'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    rows = scan(a.fonts_dir)
    fam = group(rows)
    notes_path = os.path.join(ROOT, 'notes.json')
    notes = json.load(open(notes_path, encoding='utf-8')) if os.path.exists(notes_path) else {}
    notes = {k: v for k, v in notes.items() if not k.startswith('_')}
    print('%d files, %d families' % (len(rows), len(fam)))
    for n, rs in fam.items():
        print('  %-28s %2d styles  hebrew=%-7s latin=%-7s %s' % (n, len(rs), max((r['hebrew'] for r in rs), key=['none', 'partial', 'full'].index),
              max((r['latin'] for r in rs), key=['none', 'partial', 'full'].index), '' if n in notes else '(no notes yet)'))
    for n in notes:
        if n not in fam:
            print('  note for unknown family: %s' % n, file=sys.stderr)
    if a.check:
        return
    json.dump({'families': {n: {'notes': notes.get(n, {}), 'fonts': rs} for n, rs in fam.items()}}, open(os.path.join(SKILL, 'catalog.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    open(os.path.join(SKILL, 'FONTS.md'), 'w', encoding='utf-8').write(markdown(fam, notes))
    print('wrote my-fonts/catalog.json and my-fonts/FONTS.md')


if __name__ == '__main__':
    main()
